import assert from "node:assert/strict";
import { launchBrowser, browserBaseUrl } from "../harness.mjs";
const browser = await launchBrowser();
try {
  const context = await browser.newContext();
  await context.addCookies([{ name: "activeVenue", value: "clipboard-venue", url: browserBaseUrl() }]);
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${browserBaseUrl()}/login`);
  await page.getByLabel("Email", { exact: true }).fill("admin@local.test");
  await page.getByLabel("Password", { exact: true }).fill("local-smoke-only");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.waitForURL(`${browserBaseUrl()}/`);
  await page.goto(`${browserBaseUrl()}/schedule/2026-12-07`);
  const trigger = page.getByRole("button", { name: /^(Add a shift for|Edit .+'s shift on)/ }).first();
  await trigger.click();
  const dialog = page.getByRole("dialog");
  await dialog.waitFor();
  assert.equal(await dialog.getByRole("button", { name: "Working", exact: true }).evaluate(el => el === document.activeElement), true);
  await dialog.getByLabel("Shift start time").fill("06:15");
  page.once("dialog", prompt => prompt.dismiss());
  await page.keyboard.press("Escape");
  assert.equal(await dialog.count(), 1, "Declining discard retains the editor");
  assert.equal(await dialog.getByLabel("Shift start time").inputValue(), "06:15");
  page.once("dialog", prompt => prompt.accept());
  await page.keyboard.press("Escape");
  await dialog.waitFor({ state: "detached" });
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true, "Closing restores grid focus");
  await trigger.click();
  await dialog.getByRole("button", { name: "Off", exact: true }).click();
  await dialog.getByRole("button", { name: "Save", exact: true }).click();
  await dialog.waitFor({ state: "detached" });
  await trigger.click();
  assert.equal(await dialog.getByRole("button", { name: "Off", exact: true }).getAttribute("aria-pressed"), "true");
  await dialog.getByRole("button", { name: "Clear shift", exact: true }).click();
  await dialog.waitFor({ state: "detached" });
  assert.deepEqual(errors, []);
  console.log("Schedule dialog focus, unsaved edits, discard, save/reopen and clear passed.");
} finally { await browser.close(); }
