import assert from "node:assert/strict";
import { launchBrowser, browserBaseUrl } from "../harness.mjs";
const browser = await launchBrowser();
const base = browserBaseUrl();
try {
  const context = await browser.newContext();
  await context.addCookies([{ name: "activeVenue", value: "clipboard-venue", url: base }]);
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  await page.goto(`${base}/login`);
  await page.getByLabel("Email", { exact: true }).fill("admin@local.test");
  await page.getByLabel("Password", { exact: true }).fill("local-smoke-only");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.waitForURL(`${base}/`);
  await page.goto(`${base}/recipes?q=Clipboard&sort=name&new=1`);
  await page.evaluate(() => { window.urlStateMarker = "same-document"; });
  assert.equal(await page.getByLabel("Filter recipes").inputValue(), "Clipboard");
  await page.getByLabel("Filter recipes").fill("Nested");
  await page.waitForURL(url => url.searchParams.get("q") === "Nested");
  await page.getByLabel("Sort recipes").selectOption("cost");
  await page.waitForURL(url => url.searchParams.get("sort") === "cost");
  await page.goBack();
  await page.waitForURL(url => url.searchParams.get("sort") === "name");
  assert.equal(await page.getByLabel("Sort recipes").inputValue(), "name");
  await page.getByRole("link", { name: "Clipboard Nested Dish", exact: true }).click();
  const inspector = page.getByRole("dialog");
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  assert.equal(new URL(page.url()).searchParams.get("new"), "1");
  const deepLink = page.url();
  await inspector.getByRole("link", { name: "Clipboard Sauce", exact: true }).click();
  await inspector.getByRole("heading", { name: "Clipboard Sauce", exact: true }).first().waitFor();
  await page.goBack();
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  await page.goForward();
  await inspector.getByRole("heading", { name: "Clipboard Sauce", exact: true }).first().waitFor();
  assert.equal(await page.evaluate(() => window.urlStateMarker), "same-document");
  await page.goto(deepLink);
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  await inspector.getByLabel("Standard yield quantity", { exact: true }).fill("0");
  // Browser navigation must retain invalid/unsaved edits just like Close.
  await page.evaluate(() => history.pushState(null, "", location.href + "&checkpoint=1"));
  await page.goBack();
  await inspector.getByRole("alert").filter({ hasText: "Some edits have not saved" }).waitFor();
  assert.equal(await inspector.getByLabel("Standard yield quantity", { exact: true }).inputValue(), "0");
  await inspector.getByRole("button", { name: "Discard unsaved edits and close", exact: true }).click();
  await inspector.waitFor({ state: "detached" });
  assert.equal(new URL(page.url()).searchParams.get("q"), "Nested");
  await page.goto(`${base}/items?q=Clipboard&category=Dairy`);
  assert.equal(await page.getByLabel("Search ingredients").inputValue(), "Clipboard");
  await page.evaluate(() => { window.urlStateMarker = "ingredient-navigation"; });
  await page.getByLabel("Search ingredients").fill("Butter");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await page.waitForURL(url => url.searchParams.get("q") === "Butter");
  await page.goBack();
  await page.waitForURL(url => url.searchParams.get("q") === "Clipboard");
  assert.equal(await page.getByLabel("Search ingredients").inputValue(), "Clipboard");
  assert.equal(await page.evaluate(() => window.urlStateMarker), "ingredient-navigation");
  await page.goto(`${base}/vendors/invoices?q=nonexistent&vendor=unknown&sort=oldest&id=missing`);
  assert.equal(await page.getByLabel("Search invoices", { exact: true }).inputValue(), "nonexistent");
  assert.equal(await page.getByLabel("Invoice order", { exact: true }).inputValue(), "oldest");
  await page.getByLabel("Search invoices", { exact: true }).fill("new search");
  await page.getByRole("button", { name: "Filter invoices", exact: true }).click();
  await page.waitForURL(url => url.searchParams.get("q") === "new search");
  assert.equal(new URL(page.url()).searchParams.get("id"), "missing");
  await page.goBack();
  await page.waitForURL(url => url.searchParams.get("q") === "nonexistent");
  assert.equal(await page.getByLabel("Search invoices", { exact: true }).inputValue(), "nonexistent");
  await page.getByRole("button", { name: "Search actions, recipes & ingredients", exact: true }).click();
  await page.getByRole("combobox", { name: "Search actions, recipes & ingredients", exact: true }).fill("Clipboard Nested Dish");
  await page.getByRole("option").filter({ hasText: "Clipboard Nested Dish" }).click();
  await page.waitForURL(url => url.pathname === "/recipes" && url.searchParams.get("inspect") === "recipe:clipboard-dish");
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  console.log("URL filters, sorting, inspector deep links and nested history, unsaved back protection, and invoice filter history passed.");
} finally { await browser.close(); }
