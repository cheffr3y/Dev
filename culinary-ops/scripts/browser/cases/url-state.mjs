import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { PrismaClient } from "@prisma/client";
import { launchBrowser, browserBaseUrl } from "../harness.mjs";
const browser = await launchBrowser();
const db = new PrismaClient();
const fixturePrefix = "Catalog paging fixture";
const base = browserBaseUrl();
const output = "/tmp/app-navigation-review";
await mkdir(output, { recursive: true });
try {
  const context = await browser.newContext();
  await context.addCookies([{ name: "activeVenue", value: "clipboard-venue", url: base }]);
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  await page.goto(`${base}/login`);
  await page.waitForLoadState("networkidle");
  await page.getByLabel("Email", { exact: true }).fill("admin@local.test");
  await page.getByLabel("Password", { exact: true }).fill("local-smoke-only");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.waitForURL(`${base}/`);
  await page.waitForLoadState("networkidle");
  const nav = page.locator("aside").getByRole("navigation", { name: "Main navigation" });
  assert.equal(await nav.getByRole("link", { name: "Inventory", exact: true }).count(), 0);
  assert.equal(await nav.getByRole("link", { name: "Order Guides", exact: true }).count(), 0);
  await nav.getByRole("button", { name: "Purchasing & Accounting", exact: true }).click();
  await nav.getByRole("link", { name: "Invoices", exact: true }).click();
  await page.waitForURL(`${base}/invoices`);
  await page.getByRole("heading", { name: "Invoices", exact: true }).waitFor();
  await page.waitForLoadState("networkidle");
  assert.equal(await nav.locator('[aria-current="page"]').textContent(), "Invoices");
  await page.screenshot({ path: `${output}/desktop-invoices.png`, caret: "initial" });
  await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
  assert.equal(await nav.getByRole("link", { name: "Home Meal Replacement", exact: true }).getAttribute("title"), "Home Meal Replacement");
  await page.getByRole("button", { name: "Expand sidebar", exact: true }).click();
  await page.goto(`${base}/recipes?q=Clipboard&sort=name&new=1`);
  await page.waitForLoadState("networkidle");
  await page.evaluate(() => { window.urlStateMarker = "same-document"; });
  assert.equal(await page.getByLabel("Filter recipes").inputValue(), "Clipboard");
  await page.getByLabel("Filter recipes").fill("Nested");
  await page.waitForURL(url => url.searchParams.get("q") === "Nested");
  await page.getByLabel("Sort recipes").selectOption("cost");
  await page.waitForURL(url => url.searchParams.get("sort") === "cost");
  await page.goBack();
  await page.waitForURL(url => url.searchParams.get("sort") === "name");
  await page.waitForFunction(() => document.querySelector('select[aria-label="Sort recipes"]')?.value === "name");
  assert.equal(await page.getByLabel("Sort recipes").inputValue(), "name");
  await page.getByRole("link", { name: "Clipboard Nested Dish", exact: true }).click();
  const inspector = page.getByRole("dialog");
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  assert.equal(new URL(page.url()).searchParams.get("new"), "1");
  const deepLink = page.url();
  await inspector.getByRole("link", { name: "Clipboard Sauce", exact: true }).click();
  await inspector.getByRole("heading", { name: "Clipboard Sauce", exact: true }).first().waitFor();
  await page.goBack();
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  await page.goForward();
  await inspector.getByRole("heading", { name: "Clipboard Sauce", exact: true }).first().waitFor();
  assert.equal(await page.evaluate(() => window.urlStateMarker), "same-document");
  await page.goto(deepLink);
  await page.waitForLoadState("networkidle");
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  await inspector.getByLabel("Standard yield quantity", { exact: true }).fill("0");
  // Browser navigation must retain invalid/unsaved edits just like Close.
  await page.evaluate(() => history.pushState(null, "", location.href + "&checkpoint=1"));
  await page.goBack();
  await inspector.getByRole("alert").filter({ hasText: "Some edits have not saved" }).waitFor();
  assert.equal(await inspector.getByLabel("Standard yield quantity", { exact: true }).inputValue(), "0");
  await inspector.getByRole("button", { name: "Discard unsaved edits and close", exact: true }).click();
  await inspector.waitFor({ state: "detached" });
  assert.equal(new URL(page.url()).searchParams.get("q"), "Nested");
  await page.goto(`${base}/items?q=Clipboard&category=Dairy`);
  await page.waitForLoadState("networkidle");
  await page.waitForFunction(() => document.querySelector('input[aria-label="Search ingredients"]')?.value === "Clipboard");
  assert.equal(await page.getByLabel("Search ingredients").inputValue(), "Clipboard");
  await page.evaluate(() => { window.urlStateMarker = "ingredient-navigation"; });
  await page.getByLabel("Search ingredients").fill("Butter");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await page.waitForURL(url => url.searchParams.get("q") === "Butter");
  await page.goBack();
  await page.waitForURL(url => url.searchParams.get("q") === "Clipboard");
  await page.waitForFunction(() => document.querySelector('input[aria-label="Search ingredients"]')?.value === "Clipboard");
  assert.equal(await page.getByLabel("Search ingredients").inputValue(), "Clipboard");
  assert.equal(await page.evaluate(() => window.urlStateMarker), "ingredient-navigation");

  await db.item.createMany({ data: Array.from({ length: 42 }, (_, i) => ({
    name: `${fixturePrefix} ${String(i + 1).padStart(2, "0")}`,
    category: "Dairy",
    unit: "lb",
  })) });
  await page.getByLabel("Search ingredients").fill(fixturePrefix);
  await page.getByLabel("Review filter").selectOption("missing");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await page.getByText("Showing 1–40 of 42 ingredients", { exact: true }).waitFor();
  await page.getByRole("link", { name: "Next page", exact: true }).click();
  await page.getByText("Showing 41–42 of 42 ingredients", { exact: true }).waitFor();
  const ingredientUrl = new URL(page.url());
  assert.equal(ingredientUrl.searchParams.get("category"), "Dairy");
  assert.equal(ingredientUrl.searchParams.get("flag"), "missing");
  assert.equal(ingredientUrl.searchParams.get("page"), "2");
  await page.screenshot({ path: `${output}/desktop-ingredients.png`, caret: "initial" });

  await page.setViewportSize({ width: 390, height: 844 });
  const results = page.getByRole("list", { name: "Ingredient results" });
  assert.equal(await results.getByRole("listitem").count(), 2);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: `${output}/mobile-ingredients.png`, caret: "initial" });
  const ingredientLink = results.getByRole("link", { name: `${fixturePrefix} 41`, exact: true });
  await ingredientLink.click();
  await inspector.getByRole("heading", { name: `${fixturePrefix} 41`, exact: true }).waitFor();
  await inspector.getByRole("button", { name: "Close inspector", exact: true }).click();
  await inspector.waitFor({ state: "detached" });
  assert.equal(page.url(), ingredientUrl.href);
  assert.ok(await ingredientLink.evaluate(link => document.activeElement === link));
  await page.getByLabel("Review filter").selectOption("current");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await page.getByText("No ingredients match your filters.", { exact: true }).waitFor();
  assert.equal(new URL(page.url()).searchParams.has("page"), false);
  await page.getByRole("link", { name: "Reset filters", exact: true }).click();
  await page.waitForURL(`${base}/items`);
  await page.setViewportSize({ width: 1280, height: 720 });

  await page.goto(`${base}/vendors/invoices?q=nonexistent&vendor=unknown&sort=oldest&id=missing`);
  await page.waitForLoadState("networkidle");
  await page.waitForURL(url => url.pathname === "/invoices");
  assert.equal(new URL(page.url()).searchParams.get("vendor"), "unknown");
  assert.equal(new URL(page.url()).searchParams.get("id"), "missing");
  await page.waitForFunction(() => document.querySelector('input[name="q"]')?.value === "nonexistent");
  assert.equal(await page.getByLabel("Search invoices", { exact: true }).inputValue(), "nonexistent");
  assert.equal(await page.getByLabel("Invoice order", { exact: true }).inputValue(), "oldest");
  await page.getByLabel("Search invoices", { exact: true }).fill("new search");
  await page.getByRole("button", { name: "Filter invoices", exact: true }).click();
  await page.waitForURL(url => url.searchParams.get("q") === "new search");
  assert.equal(new URL(page.url()).searchParams.get("id"), "missing");
  await page.goBack();
  await page.waitForURL(url => url.searchParams.get("q") === "nonexistent");
  await page.waitForFunction(() => document.querySelector('input[name="q"]')?.value === "nonexistent");
  assert.equal(await page.getByLabel("Search invoices", { exact: true }).inputValue(), "nonexistent");
  await page.getByRole("button", { name: "Search actions, recipes & ingredients", exact: true }).click();
  await page.getByRole("combobox", { name: "Search actions, recipes & ingredients", exact: true }).fill("Clipboard Nested Dish");
  await page.getByRole("option").filter({ hasText: "Clipboard Nested Dish" }).click();
  await page.waitForURL(url => url.pathname === "/recipes" && url.searchParams.get("inspect") === "recipe:clipboard-dish");
  await inspector.getByRole("heading", { name: "Clipboard Nested Dish", exact: true }).first().waitFor();
  await page.goto(`${base}/invoices`);
  await page.waitForLoadState("networkidle");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Open navigation", exact: true }).click();
  const drawer = page.getByRole("dialog", { name: "Navigation", exact: true });
  await drawer.waitFor();
  assert.equal(await drawer.locator('[aria-current="page"]').textContent(), "Invoices");
  await page.screenshot({ path: `${output}/mobile-navigation.png`, animations: "disabled", caret: "initial" });
  await drawer.getByRole("button", { name: "Culinary & Events", exact: true }).click();
  await drawer.getByRole("link", { name: "Home Meal Replacement", exact: true }).click();
  await page.waitForURL(`${base}/to-go`);
  await drawer.waitFor({ state: "hidden" });
  await page.getByRole("heading", { name: "HMR Rollouts", exact: true }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  for (const role of ["manager", "staff"]) {
    const roleContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const rolePage = await roleContext.newPage();
    await rolePage.goto(`${base}/login`);
    await rolePage.waitForLoadState("networkidle");
    await rolePage.getByLabel("Email", { exact: true }).fill(`${role}@local.test`);
    await rolePage.getByLabel("Password", { exact: true }).fill("local-smoke-only");
    await rolePage.getByRole("button", { name: "Sign in", exact: true }).click();
    await rolePage.waitForURL(`${base}/`);
    await rolePage.getByRole("button", { name: "Open navigation", exact: true }).click();
    const roleDrawer = rolePage.getByRole("dialog", { name: "Navigation", exact: true });
    await roleDrawer.waitFor();
    await roleDrawer.getByRole("button", { name: "Purchasing & Accounting", exact: true }).click();
    assert.equal(await roleDrawer.getByRole("link", { name: "Inventory", exact: true }).count(), 0);
    assert.equal(await roleDrawer.getByRole("link", { name: "Order Guides", exact: true }).count(), 0);
    assert.equal(await roleDrawer.getByRole("link", { name: "Invoices", exact: true }).count(), role === "manager" ? 1 : 0);
    if (role === "manager") await roleDrawer.getByRole("link", { name: "Invoices", exact: true }).click();
    else await rolePage.goto(`${base}/invoices`);
    await rolePage.waitForURL(`${base}/${role === "manager" ? "invoices" : "prep-orders"}`);
    await roleContext.close();
  }
  console.log("URL filters, inspector history, invoice legacy redirects/filter history, desktop/collapsed/mobile navigation, HMR naming, and role restrictions passed.");
} finally {
  await browser.close();
  try {
    await db.item.deleteMany({ where: { name: { startsWith: fixturePrefix } } });
  } finally {
    await db.$disconnect();
  }
}
